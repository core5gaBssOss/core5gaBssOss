#!/usr/bin/env python3
"""Generate docs/R19_COMPLETENESS.md: every REL-19 OpenAPI file no NF, BSS or library code uses yet.

usage: gen_r19_deferred_register.py [--check]

A YAML counts as "used" when its file stem (e.g. TS29518_Namf_AIoT) appears anywhere in the
tracked tree outside specs/, docs/, README.md and this generator's own tracking lists. "Used" is
a lower bound for implementation, not proof of it: a referenced file can still be only partly
implemented (the V2X/A2X and AIoT parts of referenced files are listed by hand in the header).
--check exits 1 if the committed register is stale (ADR-0539)."""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SPECS = ROOT / "specs" / "5G_APIs-REL-19"
OUT = ROOT / "docs" / "R19_COMPLETENESS.md"

# Spec family -> (owning ADR, track). Every family with an unused YAML must be listed here;
# the generator fails on an unmapped one so nothing from REL-19 drops out silently.
TRACKS = {
    "ADR-0541 UAS (drones)": ["TS29255", "TS29257"],
    "ADR-0542 V2X application enabler (VAE)": ["TS29486"],
    "ADR-0543 Ambient IoT completion": ["TS29569", "TS29369"],
    "ADR-0544 Edge computing and application enablers": [
        "TS24558", "TS29558", "TS29435", "TS24549", "TS29437", "TS24550", "TS29482",
        "TS24560", "TS24283", "TS24559", "TS29549", "TS29548", "TS29530", "TS29222"],
    "ADR-0545 IMS, HSS, GBA and messaging": [
        "TS29562", "TS29563", "TS29309", "TS29577", "TS29579", "TS29392", "TS29175",
        "TS29176", "TS29538"],
    "ADR-0546 ProSe, 5MBS, PIN and remaining 5GC services": [
        "TS29555", "TS29557", "TS29559", "TS29553", "TS29586", "TS29550", "TS29578",
        "TS29583", "TS29532", "TS29580", "TS29581", "TS29556", "TS29673", "TS29675",
        "TS29526", "TS29565", "TS29566"],
    "ADR-0547 OAM (TS 28.xxx) and media (TS 26.xxx)": ["TS28", "TS26"],
}

# Files that only a test or the codegen catalog names, not an NF: still deferred.
TEST_ONLY = {"TS29532_Nmbsmf_TMGI"}


def track_of(stem):
    for track, fams in TRACKS.items():
        if any(stem.startswith(f) for f in fams):
            return track
    return None


def info(path):
    title = version = "?"
    in_info = False
    for line in path.open(encoding="utf-8", errors="replace"):
        if line.startswith("info:"):
            in_info = True
            continue
        if in_info:
            if line and not line[0].isspace():
                break
            m = re.match(r"\s{2}(title|version):\s*(.*)", line)
            if m:
                v = m.group(2).strip().strip("'\"")
                if m.group(1) == "title":
                    title = v
                else:
                    version = v
    return title, version


def used_stems():
    out = subprocess.run(
        ["git", "grep", "-ohE", r"TS[0-9]{5}_[A-Za-z0-9_-]+", "--", ".",
         ":(exclude)specs", ":(exclude)docs", ":(exclude)README.md",
         ":(exclude)scripts/docs/gen_r19_deferred_register.py"],
        cwd=ROOT, capture_output=True, text=True, check=False).stdout
    return set(out.split())


def render():
    used = used_stems()
    rows, unmapped = [], []
    for p in sorted(SPECS.glob("TS*.yaml")):
        stem = p.stem
        if stem in used and stem not in TEST_ONLY:
            continue
        track = track_of(stem)
        if track is None:
            unmapped.append(stem)
            continue
        title, version = info(p)
        rows.append((track, stem, title, version))
    if unmapped:
        sys.exit("unmapped REL-19 families (add them to TRACKS): " + ", ".join(unmapped))
    total = len(list(SPECS.glob("TS*.yaml")))
    lines = [
        "# R19 completeness register",
        "",
        "Generated by `scripts/docs/gen_r19_deferred_register.py` (ADR-0539); do not edit by hand.",
        "",
        f"The REL-19 OpenAPI set in `specs/5G_APIs-REL-19/` has **{total}** files. **{len(rows)}** of",
        "them are not used by any NF, BSS or library code yet. Each one is listed below with its",
        "owning ADR. Status for every row: **🕒 Already in Pipeline** (none of them is implemented).",
        "",
        "\"Used\" is a lower bound, not proof of conformance. A referenced file can still be only",
        "partly implemented. The known partial areas inside referenced files are tracked by hand:",
        "",
        "| Area | Referenced files | Deferred for future implementation | ADR |",
        "|---|---|---|---|",
        "| V2X / A2X policy and context | TS29525 (PCF UE policy), TS29518 (AMF), TS29510 (NRF), TS32291 (CHF) | the PCF's V2X/A2X policy parts, the AMF's V2X/A2X context, the NRF's V2X/A2X capability fields and the CHF's V2X/A2X charging data; UDM/UDR subscription data is in | ADR-0540 |",
        "| UAV in the AMF and UDM | TS29518_Namf_EventExposure, TS29503_Nudm_SDM | UAV-related AMF events and UDM subscription data; the NEF's TS29256 / UAVFlightAssistance are in | ADR-0541 |",
        "| Ambient IoT in the NRF, NSSF and CHF | TS29510, TS29531, TS32291 | AIOTF registration and discovery, AIoT slice selection inputs and AIoT charging data, all checked against the YAML | ADR-0543 |",
        "",
        "| # | Track (ADR) | YAML file | info.title | version |",
        "|---|---|---|---|---|",
    ]
    for i, (track, stem, title, version) in enumerate(sorted(rows), 1):
        lines.append(f"| {i} | {track} | `{stem}.yaml` | {title.replace('|', '/')} | {version} |")
    lines.append("")
    by_track = {}
    for track, *_ in rows:
        by_track[track] = by_track.get(track, 0) + 1
    lines += ["## Totals per track", "", "| Track | Files |", "|---|---|"]
    lines += [f"| {t} | {n} |" for t, n in sorted(by_track.items())]
    lines += [f"| **Total** | **{len(rows)}** |", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit("docs/R19_COMPLETENESS.md is stale: run scripts/docs/gen_r19_deferred_register.py")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
