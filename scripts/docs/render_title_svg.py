#!/usr/bin/env python3
"""Render the README title (docs/assets/title.svg + title-dark.svg) as outlined glyph paths.

GitHub markdown cannot colour or enlarge text, so the title is an image. Live <text> in an SVG
renders differently per browser/OS font (and some renderers break multi-colour centred <tspan>
runs), so the glyphs are converted to paths here: the result looks identical everywhere.

Font: Noto Sans Bold (SIL OFL 1.1). Needs fontTools (`pip install fonttools`).
Usage: python3 scripts/docs/render_title_svg.py [path/to/NotoSans-Bold.ttf]
"""
import pathlib
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf"
OUT = pathlib.Path(__file__).resolve().parents[2] / "docs" / "assets"
WIDTH, HEIGHT = 1600, 200
TITLE = "AI-Native 5G-Advanced Core, Charging & BSS — R19. Built Forward to 6G"

# (text, light colour, dark colour) per segment; line 2 is one gradient run.
LINE1 = [("AI-Native ", "#DB2777", "#F472B6"), ("5G-Advanced ", "#EA580C", "#FB923C"),
         ("Core, ", "#0284C7", "#38BDF8"), ("Charging ", "#16A34A", "#4ADE80"),
         ("& ", "#64748B", "#94A3B8"), ("BSS ", "#7C3AED", "#A78BFA"),
         ("— ", "#64748B", "#94A3B8"), ("R19", "#DC2626", "#F87171")]
LINE2 = "Built Forward to 6G"
GRADIENT = {"light": ("#DB2777", "#EA580C", "#7C3AED"), "dark": ("#F472B6", "#FB923C", "#A78BFA")}


def layout(font, text, size, x0, baseline):
    """Return (svg path data, advance width) for `text` starting at x0."""
    cmap, gs, hmtx = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]
    scale = size / font["head"].unitsPerEm
    pen, x = SVGPathPen(gs), x0
    for ch in text:
        name = cmap.get(ord(ch), ".notdef")
        gs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
        x += hmtx[name][0] * scale
    return pen.getCommands(), x - x0


def width(font, text, size):
    return layout(font, text, size, 0, 0)[1]


def render(font, theme):
    dark = theme == "dark"
    s1, s2 = 64, 62
    w1 = sum(width(font, t, s1) for t, _, _ in LINE1)
    if w1 > WIDTH - 40:  # keep a margin: shrink line 1 to fit
        s1 *= (WIDTH - 40) / w1
        w1 = WIDTH - 40
    x, parts = (WIDTH - w1) / 2, []
    for text, light_c, dark_c in LINE1:
        d, adv = layout(font, text, s1, x, 82)
        if d:
            parts.append(f'  <path fill="{dark_c if dark else light_c}" d="{d}"/>')
        x += adv
    w2 = width(font, LINE2, s2)
    d2, _ = layout(font, LINE2, s2, (WIDTH - w2) / 2, 170)
    g = GRADIENT[theme]
    x_lo, x_hi = (WIDTH - w2) / 2, (WIDTH + w2) / 2
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}" width="{WIDTH}" height="{HEIGHT}"
     role="img" aria-label="{TITLE.replace('&', '&amp;')}">
  <title>{TITLE.replace('&', '&amp;')}</title>
  <!-- Generated by scripts/docs/render_title_svg.py ({theme} theme); edit the script, not this
       file. Noto Sans Bold glyph outlines (SIL OFL 1.1), so it renders identically everywhere. -->
  <defs>
    <linearGradient id="g6" gradientUnits="userSpaceOnUse" x1="{x_lo:.1f}" y1="0" x2="{x_hi:.1f}" y2="0">
      <stop offset="0" stop-color="{g[0]}"/>
      <stop offset="0.5" stop-color="{g[1]}"/>
      <stop offset="1" stop-color="{g[2]}"/>
    </linearGradient>
  </defs>
{chr(10).join(parts)}
  <path fill="url(#g6)" d="{d2}"/>
</svg>
'''


def main():
    font = TTFont(FONT)
    for theme, name in (("light", "title.svg"), ("dark", "title-dark.svg")):
        (OUT / name).write_text(render(font, theme))
        print(f"wrote {OUT / name}")


if __name__ == "__main__":
    main()
