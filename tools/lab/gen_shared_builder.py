#!/usr/bin/env python3
"""Generate the lab's shared builder: compile the repository once for every image (ADR-0505).

Each deploy/docker/<nf>.Dockerfile compiles the whole repository in its own `builder` stage and
then copies one binary into its `runtime` stage, so `make lab-build` compiled the repository ~35
times (ADR-0503, Disclosed). Those builder stages are identical except for `--target`. This writes,
from the Dockerfiles themselves (never by hand, so it cannot drift from them):

  build/lab-images/builder.Dockerfile   the builder stage of one NF Dockerfile with `--target`
                                        replaced by every target the Dockerfiles build;
  build/lab-images/docker-compose.shared-builder.yml
                                        a compose override giving every service that has a
                                        `builder` stage the build context
                                        `builder: docker-image://<BUILDER_IMAGE>`. BuildKit uses a
                                        named build context in place of the Dockerfile stage of
                                        the same name, so each image's runtime stage copies from
                                        the shared builder and its own builder stage never runs.

The NF Dockerfiles are not changed: built without the override, each still compiles on its own.
Both files are under build/ (git-ignored) and regenerated on every `make lab-build-fast`.
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / 'build/lab-images'
COMPOSE = ['docker', 'compose', '-f', 'deploy/docker/docker-compose.yml',
           '-f', 'deploy/docker/docker-compose.lab.yml']
BUILDER_START = re.compile(r'^FROM\s+\S+\s+AS\s+builder\s*$', re.I | re.M)
STAGE_START = re.compile(r'^FROM\s', re.M)
TARGET = re.compile(r'cmake --build build --target ([A-Za-z0-9_.+-]+)\s*$', re.M)


def builder_stage(text):
    """The `builder` stage of a Dockerfile (its FROM line up to the next FROM), or None."""
    m = BUILDER_START.search(text)
    if not m:
        return None
    nxt = STAGE_START.search(text, m.end())
    return text[m.start():nxt.start() if nxt else len(text)]


def built_services():
    """{service: Dockerfile path} for every compose service that builds an image."""
    out = subprocess.run(COMPOSE + ['config', '--format', 'json'], cwd=ROOT, check=True,
                         capture_output=True, text=True).stdout
    services = {}
    for name, svc in json.loads(out)['services'].items():
        build = svc.get('build')
        if build:
            services[name] = pathlib.Path(build['context'], build['dockerfile']).resolve()
    return services


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--builder-image', default='5gc-lab-builder:local')
    args = ap.parse_args()

    services = built_services()
    stages, targets, using = {}, [], []
    for name, dockerfile in sorted(services.items()):
        stage = builder_stage(dockerfile.read_text())
        if stage is None:
            continue
        using.append(name)
        m = TARGET.search(stage)
        if not m:
            sys.exit(f'{dockerfile}: builder stage has no `cmake --build build --target <t>` line')
        if m.group(1) not in targets:
            targets.append(m.group(1))
        stages[dockerfile] = TARGET.sub('cmake --build build --target X', stage)

    # The shared builder is only equivalent if every builder stage is the same apart from its
    # target; stop rather than silently build something a Dockerfile would not.
    distinct = {re.sub(r'^\s*#.*$', '', s, flags=re.M) for s in stages.values()}
    distinct = {re.sub(r'\s+', ' ', s).strip() for s in distinct}
    if len(distinct) != 1:
        sys.exit('builder stages differ beyond --target; the shared builder would not be '
                 'equivalent:\n  ' + '\n  '.join(str(p.relative_to(ROOT)) for p in stages))

    template = next(iter(stages.values()))
    # A build arg is visible to RUN as an environment variable, and `cmake --build` reads this
    # one (empty: ninja's default, all cores). It is declared just before the RUN that compiles:
    # an ARG joins the cache key of every later RUN, and earlier layers must stay shared with the
    # per-NF builder stages' cache.
    compile_run = template.rfind('\nRUN ', 0, template.index('cmake --build build --target X'))
    if compile_run < 0:
        sys.exit('builder stage: no RUN instruction before `cmake --build`')
    template = (template[:compile_run] + '\nARG CMAKE_BUILD_PARALLEL_LEVEL='
                + template[compile_run:])
    builder = ('# syntax=docker/dockerfile:1\n'
               '# GENERATED by tools/lab/gen_shared_builder.py from deploy/docker/*.Dockerfile '
               '(ADR-0505) -- do not edit.\n'
               + template.replace('cmake --build build --target X',
                                  'cmake --build build --target ' + ' '.join(targets)))
    override = {'services': {name: {'build': {'additional_contexts': {
        'builder': f'docker-image://{args.builder_image}'}}} for name in using}}

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / 'builder.Dockerfile').write_text(builder)
    # JSON is valid YAML; compose reads it as an override file.
    (OUT_DIR / 'docker-compose.shared-builder.yml').write_text(json.dumps(override, indent=2) + '\n')
    print(f'shared builder: {len(targets)} targets, {len(using)} services '
          f'-> {(OUT_DIR / "builder.Dockerfile").relative_to(ROOT)}')


if __name__ == '__main__':
    main()
