#!/usr/bin/env python3
"""Generate the README "R19 at a glance" area table from docs/diagrams/architecture.json (ADR-0553).

Every tile in the architecture diagram belongs to exactly one README area below; the script fails
if a tile is unassigned or assigned twice, so the table's totals always equal the diagram's. Built
and in-pipeline counts and the tile names come from the JSON, never from this file -- only the
grouping, the ADR pointers and two disclosed status overrides are written here.

    python3 tools/diagrams/gen_readme_areas.py          # rewrite the table in README.md
    python3 tools/diagrams/gen_readme_areas.py --check  # CI: fail if README.md is stale
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[2]
START = "<!-- r19-areas:start (generated by tools/diagrams/gen_readme_areas.py; do not edit) -->"
END = "<!-- r19-areas:end -->"

# (area, diagram areas, extra tile ids, ADRs, status override or None)
# A tile id listed under "extra" is taken out of its diagram area and counted here instead.
AREAS = [
    ("Access", ["access"], [], "ADR-0550",
     "✅ Built (gNB/UE test harness) + 🕒 N3IWF/TNGF Already in Pipeline (ADR-0550, not yet tiled)"),
    ("5GC control plane", ["cp"], ["ucmf", "misc5gc"], "ADR-0546", None),
    ("SBI framework", [], ["nrf", "scp", "bsf"], "—", None),
    ("Interconnect and data network (N32 · N6)", [], ["sepp", "roam"], "—", None),
    ("Charging (CHF · Gy · CAP)", ["chg"], [], "—", None),
    ("BSS/OSS — TM Forum", ["bss"], [], "ADR-0553", None),
    ("Data stores", ["ds"], [], "—", None),
    ("AI plane", ["ai"], [], "—", None),
    ("Operations (observability · GUI · OAM)", [], ["otel", "gui", "oam"], "ADR-0547", None),
    ("Security (AAnF · NSSAAF)", [], ["aanf", "nssaaf"], "—", None),
    ("Lawful interception", [], ["li"], "—", None),
    ("V2X · A2X", ["r19-v2x"], [], "ADR-0540 · 0542 · 0551",
     "🚧 In progress (PCF V2X, PR #80) + 🕒 Already in Pipeline"),
    ("UAS — drones · UAE", ["r19-uas"], [], "ADR-0541", None),
    ("Ambient IoT", ["r19-aiot"], [], "ADR-0543", None),
    ("Edge (EES/ECS · EASDF)", ["r19-edge"], [], "ADR-0544", None),
    ("Enablers (SEAL · CAPIF · NSCE · AIMLE …)", ["r19-enab"], [], "ADR-0544", None),
    ("IMS and messaging", ["r19-ims"], [], "ADR-0545", None),
    ("ProSe · 5MBS · positioning", ["r19-prose"], ["lmf", "gmlc"], "ADR-0546", None),
]


def status(built: int, planned: int) -> str:
    if built and planned:
        return "✅ Built + 🕒 extensions Already in Pipeline"
    if built:
        return "✅ Built"
    return "🕒 Already in Pipeline"


def table() -> str:
    data = json.loads((root / "docs/diagrams/architecture.json").read_text())
    nodes = data["nodes"]
    extras = {t for a in AREAS for t in a[2]}
    seen: dict[str, str] = {}
    rows = []
    for name, areas, extra, adrs, override in AREAS:
        mine = [n for n in nodes if (n["area"] in areas and n["id"] not in extras) or n["id"] in extra]
        for n in mine:
            if n["id"] in seen:
                sys.exit(f"gen_readme_areas: tile {n['id']} is in both '{seen[n['id']]}' and '{name}'")
            seen[n["id"]] = name
        b = [n["acronym"] for n in mine if not n.get("planned")]
        p = [n["acronym"] for n in mine if n.get("planned")]
        cell = lambda xs: f"{len(xs)} — {', '.join(xs)}" if xs else "0"
        rows.append(f"| {name} | {cell(b)} | {cell(p)} | {adrs} | {override or status(len(b), len(p))} |")
    missing = [n["id"] for n in nodes if n["id"] not in seen]
    if missing:
        sys.exit(f"gen_readme_areas: tiles in no README area: {', '.join(missing)}")
    built = sum(1 for n in nodes if not n.get("planned"))
    head = [
        START,
        "",
        "| Area | Built (diagram tiles) | Already in Pipeline (diagram tiles) | ADR | Status |",
        "|---|---|---|---|---|",
    ]
    foot = [
        "",
        f"Totals: {built} built tiles, {len(nodes) - built} in pipeline — the same tiles as the "
        "architecture diagram below; each tile is counted in exactly one area. A ✅ area can still "
        "have deferred items inside a built function: see `docs/COMPONENT_STATUS.md` and ADR-0553.",
        "",
        END,
    ]
    return "\n".join(head + rows + foot)


def main() -> int:
    path = root / "README.md"
    text = path.read_text()
    if START not in text or END not in text:
        print(f"README.md has no {START} ... {END} block")
        return 1
    before, rest = text.split(START, 1)
    after = rest.split(END, 1)[1]
    new = before + table() + after
    if "--check" in sys.argv:
        if new != text:
            print("README.md 'R19 at a glance' table is stale -- run tools/diagrams/gen_readme_areas.py")
            return 1
        print("README.md 'R19 at a glance' table matches architecture.json")
        return 0
    path.write_text(new)
    print("wrote README.md 'R19 at a glance' table")
    return 0


if __name__ == "__main__":
    sys.exit(main())
