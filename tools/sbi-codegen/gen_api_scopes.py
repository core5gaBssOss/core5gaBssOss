#!/usr/bin/env python3
"""Writes libs/sbi-core/src/api_scopes.inc: for every REL-19 API whose YAML declares the
oAuth2ClientCredentials security scheme, the apiName of its `servers` URL ({apiRoot}/<apiName>/<v>)
and the service-level OAuth2 scope its `flows.*.scopes` declares (ADR-0499 phase 1).

The service-level scope is the declared scope without a ':' (resource/operation scopes carry one,
TS 29.500 6.7.3). An API declaring none is given its only scope if it declares exactly one; any
other case is reported and left out rather than guessed.

Usage: gen_api_scopes.py <specs/5G_APIs-REL-19> <output .inc>
"""
import glob
import os
import re
import sys

import yaml


def main(spec_dir: str, out_path: str) -> int:
    table: dict[str, str] = {}
    skipped = []
    for path in sorted(glob.glob(os.path.join(spec_dir, "TS*.yaml"))):
        try:
            with open(path, encoding="utf-8") as f:
                doc = yaml.safe_load(f)
        except yaml.YAMLError:
            continue
        if not isinstance(doc, dict) or "paths" not in doc:
            continue
        schemes = (doc.get("components") or {}).get("securitySchemes") or {}
        flows = (schemes.get("oAuth2ClientCredentials") or {}).get("flows") or {}
        scopes = sorted({s for fl in flows.values() for s in (fl.get("scopes") or {})})
        if not scopes:
            continue
        plain = [s for s in scopes if ":" not in s]
        if len(plain) == 1:
            scope = plain[0]
        elif not plain and len(scopes) == 1:
            scope = scopes[0]
        else:
            skipped.append((os.path.basename(path), scopes))
            continue
        for server in doc.get("servers") or []:
            m = re.match(r"\{apiRoot\}/([^/]+)/", server.get("url", ""))
            if m is None:
                continue
            name = m.group(1)
            if table.get(name, scope) != scope:
                skipped.append((os.path.basename(path), [name, table[name], scope]))
                continue
            table[name] = scope
    for f, s in skipped:
        print(f"skipped {f}: {s}", file=sys.stderr)
    with open(out_path, "w", encoding="utf-8") as out:
        out.write("// Generated by tools/sbi-codegen/gen_api_scopes.py from specs/5G_APIs-REL-19 "
                  "-- do not edit.\n")
        out.write("// {apiName, service-level OAuth2 scope} (ADR-0499).\n")
        for name, scope in sorted(table.items()):
            out.write(f'{{"{name}", "{scope}"}},\n')
    print(f"{len(table)} APIs, {len(skipped)} skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
